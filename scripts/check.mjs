import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {groupOf,filterRecords,sortRecords,safeUrl,csv,validateReviewBackup} from '../public/core.js';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const records=JSON.parse(readFileSync(path.join(root,'public/records.json'),'utf8'));
const discovery=JSON.parse(readFileSync(path.join(root,'public/discovery.json'),'utf8'));
assert.equal(records.length,17);assert.equal(new Set(records.map(r=>r.id)).size,17);
assert.equal(discovery.length,32);
assert.deepEqual(['news','official','research','project'].map(g=>records.filter(r=>groupOf(r)===g).length),[9,4,3,1]);
for(const r of records){assert.ok(r.title&&r.en&&r.bn&&r.source&&r.flag);assert.ok(safeUrl(r.url));assert.equal(r.decision,'Pending');if(r.date){assert.match(r.date,/^\d{4}-\d{2}-\d{2}$/);assert.ok(!Number.isNaN(Date.parse(r.date)));}}
assert.equal(records.find(r=>r.id==='BSW-014').date,'');
assert.equal(records.filter(r=>r.documentId==='10.31389/jied.149').length,1);
assert.ok(records.find(r=>r.id==='BSW-010').alternateUrl.includes('econstor'));
const ids=f=>filterRecords(records,f).map(r=>r.id).sort();
assert.deepEqual(ids({river:'Someshwari'}),['BSW-007','BSW-012']);
assert.deepEqual(ids({river:'Buri Teesta'}),['BSW-006']);
assert.deepEqual(ids({river:'Teesta'}),['BSW-002','BSW-009']);
assert.deepEqual(ids({search:'Shomeshwari'}),ids({search:'সোমেশ্বরী'}));
assert.deepEqual(ids({district:'Netrokona',category:'research'}),['BSW-012']);
assert.deepEqual(ids({category:'official',sourceLanguage:'Bangla'}),['BSW-014','BSW-015','BSW-016','BSW-017']);
assert.deepEqual(ids({year:'2010 (act year)'}),['BSW-014']);
assert.ok(filterRecords(records,{dateFrom:'2026-01-01'}).every(r=>r.date>='2026-01-01'));
assert.equal(filterRecords(records,{dateFrom:'2026-01-01'}).some(r=>r.id==='BSW-014'),false);
assert.deepEqual(ids({dateFrom:'2026-01-01',dateTo:'2026-01-31'}),['BSW-009','BSW-017']);
assert.deepEqual(ids({material:'gravel',district:'Sylhet'}),['BSW-004','BSW-005']);
assert.deepEqual(ids({search:'a phrase that is absent xyzabc'}),[]);
for(const s of ['newest','oldest'])assert.ok(sortRecords(records,s).slice(-2).every(r=>!r.date));
const reviews={'BSW-001':{decision:'Accept',notes:'Check the leased boundary'}};
assert.equal(filterRecords(records,{decision:'Accept'},reviews)[0].id,'BSW-001');
assert.equal(filterRecords(records,{decision:'Pending'},reviews).length,16);
assert.deepEqual(validateReviewBackup({kind:'bangladesh-sand-watch-review',schemaVersion:1,reviews},records),reviews);
assert.throws(()=>validateReviewBackup({kind:'bangladesh-sand-watch-review',schemaVersion:1,reviews:{bogus:{decision:'Accept',notes:''}}},records));
assert.throws(()=>validateReviewBackup({kind:'bangladesh-sand-watch-review',schemaVersion:1,reviews:{'BSW-001':{decision:'Verified',notes:''}}},records));
assert.equal(safeUrl('javascript:alert(1)'),'');
const data=csv([['title','notes'],['বালু','quote " and, comma\nnewline'],['=SUM(A1:A2)','@malicious']]);
assert.ok(data.startsWith('\uFEFF'));assert.ok(data.includes('"quote "" and, comma\nnewline"'));assert.ok(data.includes('"\'=SUM(A1:A2)"'));assert.ok(data.includes('"\'@malicious"'));
const html=readFileSync(path.join(root,'public/index.html'),'utf8');
const htmlIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(htmlIds).size,htmlIds.length);
const app=readFileSync(path.join(root,'public/app.js'),'utf8');
const dynamicIds=['detail-decision','detail-notes','review-form'];
for(const m of app.matchAll(/\$\('#([a-z-]+)'\)/g))assert.ok(htmlIds.includes(m[1])||dynamicIds.includes(m[1]),'Missing DOM target '+m[1]);
for(const m of html.matchAll(/(?:src|href)="([^"#]+)"/g)){if(!/^(https?:|data:)/.test(m[1]))assert.ok(existsSync(path.join(root,'public',m[1])),m[1]+' missing');}
assert.ok(existsSync(path.join(root,'public/assets/NotoSansBengali.ttf')));
execFileSync(process.execPath,['--check',path.join(root,'public/app.js')]);
execFileSync(process.execPath,['--check',path.join(root,'public/core.js')]);
execFileSync(process.execPath,['--check',path.join(root,'public/visuals.js')]);
console.log('Passed: 17 records, provenance and dates, bilingual aliases, combined filters, sorting, review import/export rules, CSV safety, syntax, DOM targets, and static assets.');
